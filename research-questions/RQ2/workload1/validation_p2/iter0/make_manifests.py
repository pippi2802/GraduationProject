#!/usr/bin/env python3
"""Writes the online-validation pods (procedure 2, iteration 0) of the video workload from budgets.csv (standard library only).

    python3 make_manifests.py

Input: budgets.csv, exported by analysis_procedure2/analysis_workload1.ipynb (section 6.4). Columns: scenario, route (route1, route2b, hwm),
p (0.1, 0.01, 0.001 or "all" for Route 3), runtime_us, period_us, admitted. A budget that is not admitted is skipped (the driver would reject it).

One self-contained file per scenario x route x tolerance x interference in pods/<scenario>/<route>/<p>_<none|memory>.yaml: the RtClaimParameters
with runtime = the budget (us) of period 41667 us, the ResourceClaimTemplate and the Pod (multi-core also a ConfigMap with the config of launch.py).
Route 3 has no tolerance: hwm/all_none.yaml and all_memory.yaml. Also runs.csv (what each run is, where it runs, where its files appear on the node
and where to save them) and step5_input/budgets.csv. The memory enemy is NOT in a pod: run_validation.sh starts it on the node around the runs whose file name ends in _memory.yaml.

The workload is exactly the one of the profiling: single-core arguments from ../../pods/single_core_pod.yaml, multi-core config from ../../configs/multi_core.json
(only jobs and output change).

To change a budget, edit budgets.csv (or re-export it from the notebook) and run this again."""
import csv, json, pathlib, re

HERE = pathlib.Path(__file__).resolve().parent
WORKLOAD = HERE.parents[1]                     # research-questions/RQ2/workload
JOBS = 20000                                   # jobs per instance: 13.9 minutes at the 41.667 ms period, about 20 expected exceedances at p = 1e-3
IMAGE = "pippina2/rq2-workload:v2"
NODE_DIR = "/var/lib/rq2/results/video_validation_p2"      # hostPath on the node; the pod writes <run id>_instance<N>.csv there
# each scenario is validated on the node that did NOT profile it (profiling: single-core on worker6, multi-core on worker7)
SCEN = {
    "multi_core": dict(short="multi", node="rt-k8s-worker-6", cpus=[1, 2], enemy_cpus="3,0"),
    "single_core": dict(short="single", node="rt-k8s-worker-7", cpus=[1], enemy_cpus="2,3,0"),
}
ROUTES = {"route1": ("r1", "Route 1: Q = C_p of the stress runs x alpha_drift"),
          "route2b": ("r2b", "Route 2: Q = C_p of the baselines x alpha_platform(m) x alpha_drift"),
          "hwm": ("hwm", "Route 3 (HWM, capped at the admission limit): Q = min(largest C of the stress runs x alpha_drift, 0.95 T), one budget for every tolerance")}
TOL = {"0.1": "p1e-1", "0.01": "p1e-2", "0.001": "p1e-3"}
M = {"single_core": 3, "multi_core": 2}          # enemy cores of the profiling (the label of Route 2)
COND = {"none": ("none", "without interference"), "memory": ("mem", "with the memory enemy (started on the node around the run)")}
ENEMY_KB = {"memory": 2662400}                   # enemy buffer: 10 x the last-level cache, as in the profiling

multi_cfg = json.load(open(WORKLOAD / "configs" / "multi_core.json"))
single_args = re.findall(r'^\s+- "(--[^"]+)"', (WORKLOAD / "pods" / "single_core_pod.yaml").read_text(), re.M)
assert any(a.startswith("--jobs=") for a in single_args) and any(a.startswith("--output=") for a in single_args)


def multi_config(run_id):
    cfg = json.loads(json.dumps(multi_cfg))
    for inst in cfg["instances"]:
        inst["jobs"] = JOBS
        inst["output"] = f"/results/{run_id}_{inst['instance_id']}.csv"
    return json.dumps(cfg, indent=2)


def single_arg_lines(run_id):
    out = []
    for a in single_args:
        if a.startswith("--jobs="):
            a = f"--jobs={JOBS}"
        elif a.startswith("--output="):
            a = f"--output=/results/{run_id}_instance0.csv"
        out.append(f'        - "{a}"')
    return "\n".join(out)


def pod_file(scen, route, ptag, cond, row):
    s = SCEN[scen]
    rshort, rdesc = ROUTES[route]
    cshort, cdesc = COND[cond]
    run_id = f"rq2-val2-vid-{s['short']}-{rshort}-{ptag}-{cshort}"
    runtime, period = int(row["runtime_us"]), int(row["period_us"])
    head = f"""# id: {run_id}
# Online validation of the video workload, {scen.replace('_', '-')}, {rdesc}
# {'no tolerance (one budget for every p)' if row['p'] == 'all' else 'tolerance p = ' + row['p']}, {cdesc}
# Reservation: runtime {runtime} us of period {period} us (Q/T = {runtime / period:.3f}), from budgets.csv. {JOBS} jobs per instance; cpus {s['cpus']}; pinned to {s['node']}.
# Generated by make_manifests.py: edit budgets.csv and regenerate instead of editing this file.
---
"""
    params = f"""apiVersion: rt.resource.example.com/v1alpha1
kind: RtClaimParameters
metadata: {{ namespace: rq2, name: "{run_id}-params" }}
spec: {{ count: {len(s['cpus'])}, runtime: {runtime}, period: {period}, requestedCpus: {s['cpus']} }}
---
apiVersion: resource.k8s.io/v1alpha2
kind: ResourceClaimTemplate
metadata: {{ namespace: rq2, name: "{run_id}-claim" }}
spec:
  spec:
    resourceClassName: rt.example.com
    parametersRef: {{ apiGroup: rt.resource.example.com, kind: RtClaimParameters, name: "{run_id}-params" }}
---
"""
    pod_head = f"""apiVersion: v1
kind: Pod
metadata:
  namespace: rq2
  name: "{run_id}"
  labels: {{ app: rq2-workload, role: worker, validation: "true", interference: "{cond}" }}
spec:
  restartPolicy: Never
  nodeSelector: {{ experiment-model: rq2, kubernetes.io/hostname: {s['node']} }}
  tolerations: [{{ operator: Exists }}]
  containers:
    - name: rt-video
      image: {IMAGE}
      imagePullPolicy: IfNotPresent
"""
    tail = f"""  resourceClaims:
    - {{ name: rtcpu, source: {{ resourceClaimTemplateName: "{run_id}-claim" }} }}
  volumes:
    - name: results
      hostPath: {{ path: {NODE_DIR}, type: DirectoryOrCreate }}
"""
    if scen == "multi_core":
        cfg = "\n".join("    " + line for line in multi_config(run_id).splitlines())
        cm = f"""apiVersion: v1
kind: ConfigMap
metadata: {{ namespace: rq2, name: "{run_id}-config" }}
data:
  multi_core.json: |
{cfg}
---
"""
        pod = pod_head + """      command: ["python3", "launch.py"]
      args: ["/cfg/multi_core.json"]
      securityContext: { capabilities: { add: ["SYS_NICE", "IPC_LOCK"] } }
      resources: { claims: [{ name: rtcpu }] }
      volumeMounts: [{ name: results, mountPath: /results }, { name: cfg, mountPath: /cfg }]
""" + tail + f"""    - name: cfg
      configMap: {{ name: "{run_id}-config" }}
"""
        return run_id, head + cm + params + pod
    pod = pod_head + f"""      command: ["python3", "rt_video.py"]
      args:
{single_arg_lines(run_id)}
      securityContext: {{ capabilities: {{ add: ["SYS_NICE", "IPC_LOCK"] }} }}
      resources: {{ claims: [{{ name: rtcpu }}] }}
      volumeMounts: [{{ name: results, mountPath: /results }}]
""" + tail
    return run_id, head + params + pod


def admitted(row):
    return str(row["admitted"]).strip().lower() == "true"


def main():
    rows = {}
    for r in csv.DictReader(open(HERE / "budgets.csv")):
        p = r["p"] if r["p"] == "all" else f"{float(r['p']):g}"
        rows[(r["scenario"], r["route"], p)] = dict(r, p=p)
    runs = []
    for scen, s in SCEN.items():
        for route in ROUTES:
            out = HERE / "pods" / scen / route
            for p, ptag in (TOL.items() if route != "hwm" else [("all", "all")]):
                row = rows[(scen, route, p)]
                if not admitted(row):                      # the driver would reject this reservation: nothing to validate
                    print(f"skipped (not admitted, Q/T = {int(row['runtime_us']) / int(row['period_us']):.2f}): {scen} {route} p={p}")
                    continue
                for cond in COND:
                    run_id, text = pod_file(scen, route, ptag, cond, row)
                    path = out / f"{ptag}_{cond}.yaml"
                    out.mkdir(parents=True, exist_ok=True)
                    path.write_text(text)
                    runs.append(dict(run_id=run_id, scenario=scen, route=route, p=p, interference=cond, node=s["node"],
                                     enemy_cpus=s["enemy_cpus"] if cond != "none" else "", enemy_kb=ENEMY_KB.get(cond, ""), runtime_us=row["runtime_us"], period_us=row["period_us"], jobs=JOBS,
                                     pod_file=str(path.relative_to(HERE)), node_files=f"{NODE_DIR}/{run_id}_instance*.csv",
                                     save_results_in=f"results/{scen}/{route}/{ptag}_{cond}"))
    # the same budgets in step 4's format, for step 5's validate.py:  python3 validate.py check --step4 <this folder>/step5_input --results <this folder>/results
    label = {"route1": lambda s: "Route 1", "route2b": lambda s: f"Route 2b (m={M[s]})", "hwm": lambda s: "HWM"}
    out5 = HERE / "step5_input"
    out5.mkdir(exist_ok=True)
    with open(out5 / "budgets.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["scenario", "route", "p", "Q_ms", "Q_over_T", "runtime_us", "period_us", "admitted"])
        for (scen, route, p), r in rows.items():
            if not admitted(r):
                continue
            for pp in ([0.001, 0.01, 0.1] if p == "all" else [float(p)]):
                q, T = int(r["runtime_us"]), int(r["period_us"])
                w.writerow([scen, label[route](scen), pp, q / 1000, q / T, q, T, q / T <= 0.95])
    with open(HERE / "runs.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(runs[0]))
        w.writeheader()
        w.writerows(runs)
    print(f"wrote {len(runs)} pods under {HERE / 'pods'} and runs.csv")


if __name__ == "__main__":
    main()
