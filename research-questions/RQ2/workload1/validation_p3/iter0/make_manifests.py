#!/usr/bin/env python3
"""Writes the online-validation pods of procedure 3 (iteration 0) of the video workload from budgets.csv (standard library only).

    python3 make_manifests.py

Input: budgets.csv, exported by analysis_procedure3/analysis_workload1.ipynb (section 5.5): the budgets of the two levels (relaxed, strict), Route 1 and Route 2,
Q* = max(Q_p, Q_(m,k)). Columns: scenario, route, level, p, m, k, eps, Q_p_ms, Q_mk_ms, Q_ms, extra_over_Q_p, dominated_by, Q_over_T, runtime_us, period_us, admitted.
A budget that is not admitted is skipped (the driver would reject it).

One self-contained file per scenario x route x level x interference in pods/<scenario>/<route>/<level>_<memory>.yaml: the RtClaimParameters with runtime = Q* (us)
of period 41667 us, the ResourceClaimTemplate and the Pod (multi-core also a ConfigMap with the config of launch.py). Also runs.csv (what each run is, where it runs, where its files appear on the node and where to save them).
The interference is NOT in a pod: the memory enemy is started on the node around the runs whose file name ends in _memory.yaml (run_validation.sh does it).

To change a budget, edit budgets.csv (or re-export it from the notebook) and run this again."""
import csv, pathlib, json, re

HERE = pathlib.Path(__file__).resolve().parent
JOBS = 30000                                  # jobs per instance: 20.8 minutes at the 41.667 ms period, about 30 expected exceedances at p = 1e-3
IMAGE = "pippina2/rq2-workload:v2"
NODE_DIR = "/var/lib/rq2/results/video_validation_p3"      # hostPath on the node; the pod writes <run id>_instance<N>.csv there
# each scenario is validated on the node that did NOT profile it (profiling: single-core on worker6, multi-core on worker7)
SCEN = {
    "multi_core": dict(short="multi", node="rt-k8s-worker-6", cpus=[1, 2], enemy_cpus="3,0"),
    "single_core": dict(short="single", node="rt-k8s-worker-7", cpus=[1], enemy_cpus="2,3,0"),
}
ROUTES = {"route1": ("r1", "Route 1: Q_p = C_p of the stress runs x alpha_drift"),
          "route2b": ("r2b", "Route 2: Q_p = C_p of the baselines x alpha_platform(m) x alpha_drift")}
LEVEL = {"relaxed": "rel", "strict": "str"}
COND = {"memory": ("mem", "with the memory enemy (started on the node around the run)")}
ENEMY_KB = {"memory": 2662400}                   # enemy buffer: 10 x the last-level cache, as in the profiling

# the workload is exactly the one of the profiling: single-core arguments from ../../../pods/single_core_pod.yaml, multi-core config from ../../../configs/multi_core.json (only jobs and output change)
WORKLOAD = HERE.parents[1]                     # research-questions/RQ2/workload1
multi_cfg = json.load(open(WORKLOAD / "configs" / "multi_core.json"))
single_args = re.findall(r'^\s+- "(--[^"]+)"', (WORKLOAD / "pods" / "single_core_pod.yaml").read_text(), re.M)
assert any(a.startswith("--jobs=") for a in single_args) and any(a.startswith("--output=") for a in single_args)


def multi_config(run_id):
    cfg = json.loads(json.dumps(multi_cfg))
    for inst in cfg["instances"]:
        inst["jobs"] = JOBS
        inst["output"] = f"/results/{run_id}_{inst['instance_id']}.csv"
    return json.dumps(cfg, indent=2)


def single_arg_lines(run_id):
    out = []
    for a in single_args:
        if a.startswith("--jobs="):
            a = f"--jobs={JOBS}"
        elif a.startswith("--output="):
            a = f"--output=/results/{run_id}_instance0.csv"
        out.append(f'        - "{a}"')
    return "\n".join(out)


def pod_file(scen, route, level, cond, row):
    s = SCEN[scen]
    rshort, rdesc = ROUTES[route]
    cshort, cdesc = COND[cond]
    run_id = f"rq2-val3-vid-{s['short']}-{rshort}-{LEVEL[level]}-{cshort}"
    runtime, period = int(row["runtime_us"]), int(row["period_us"])
    head = f"""# id: {run_id}
# Procedure 3 online validation of the video workload, {scen.replace('_', '-')}, {rdesc}
# level {level}: rate p = {row['p']}, window (m,k) = ({row['m']},{row['k']}) with eps = {row['eps']}; Q* = max(Q_p {float(row['Q_p_ms']):.3f} ms, Q_(m,k) {float(row['Q_mk_ms']):.3f} ms): {row['dominated_by']} dominates
# {cdesc}. Reservation: runtime {runtime} us of period {period} us (Q/T = {runtime / period:.3f}), from budgets.csv. {JOBS} jobs per instance; cpus {s['cpus']}; pinned to {s['node']}.
# Generated by make_manifests.py: edit budgets.csv and regenerate instead of editing this file.
---
"""
    params = f"""apiVersion: rt.resource.example.com/v1alpha1
kind: RtClaimParameters
metadata: {{ namespace: rq2, name: "{run_id}-params" }}
spec: {{ count: {len(s['cpus'])}, runtime: {runtime}, period: {period}, requestedCpus: {s['cpus']} }}
---
apiVersion: resource.k8s.io/v1alpha2
kind: ResourceClaimTemplate
metadata: {{ namespace: rq2, name: "{run_id}-claim" }}
spec:
  spec:
    resourceClassName: rt.example.com
    parametersRef: {{ apiGroup: rt.resource.example.com, kind: RtClaimParameters, name: "{run_id}-params" }}
---
"""
    pod_head = f"""apiVersion: v1
kind: Pod
metadata:
  namespace: rq2
  name: "{run_id}"
  labels: {{ app: rq2-workload, role: worker, validation: "true", interference: "{cond}" }}
spec:
  restartPolicy: Never
  nodeSelector: {{ experiment-model: rq2, kubernetes.io/hostname: {s['node']} }}
  tolerations: [{{ operator: Exists }}]
  containers:
    - name: rt-video
      image: {IMAGE}
      imagePullPolicy: IfNotPresent
"""
    tail = f"""  resourceClaims:
    - {{ name: rtcpu, source: {{ resourceClaimTemplateName: "{run_id}-claim" }} }}
  volumes:
    - name: results
      hostPath: {{ path: {NODE_DIR}, type: DirectoryOrCreate }}
"""
    if scen == "multi_core":
        cfg = "\n".join("    " + line for line in multi_config(run_id).splitlines())
        cm = f"""apiVersion: v1
kind: ConfigMap
metadata: {{ namespace: rq2, name: "{run_id}-config" }}
data:
  multi_core.json: |
{cfg}
---
"""
        pod = pod_head + """      command: ["python3", "launch.py"]
      args: ["/cfg/multi_core.json"]
      securityContext: { capabilities: { add: ["SYS_NICE", "IPC_LOCK"] } }
      resources: { claims: [{ name: rtcpu }] }
      volumeMounts: [{ name: results, mountPath: /results }, { name: cfg, mountPath: /cfg }]
""" + tail + f"""    - name: cfg
      configMap: {{ name: "{run_id}-config" }}
"""
        text = head + cm + params + pod
    else:
        text = head + params + pod_head + f"""      command: ["python3", "rt_video.py"]
      args:
{single_arg_lines(run_id)}
      securityContext: {{ capabilities: {{ add: ["SYS_NICE", "IPC_LOCK"] }} }}
      resources: {{ claims: [{{ name: rtcpu }}] }}
      volumeMounts: [{{ name: results, mountPath: /results }}]
""" + tail
    return run_id, text


def main():
    rows = {(r["scenario"], r["route"], r["level"]): r for r in csv.DictReader(open(HERE / "budgets.csv"))}
    runs = []
    for scen, s in SCEN.items():
        for route in ROUTES:
            out = HERE / "pods" / scen / route
            for level in LEVEL:
                row = rows[(scen, route, level)]
                if str(row["admitted"]).strip().lower() != "true":     # the driver would reject this reservation: nothing to validate
                    print(f"skipped (not admitted, Q/T = {float(row['Q_over_T']):.2f}): {scen} {route} {level}")
                    continue
                for cond in COND:
                    run_id, text = pod_file(scen, route, level, cond, row)
                    path = out / f"{level}_{cond}.yaml"
                    out.mkdir(parents=True, exist_ok=True)
                    path.write_text(text)
                    runs.append(dict(run_id=run_id, scenario=scen, route=route, level=level, p=row["p"], m=row["m"], k=row["k"], interference=cond, node=s["node"],
                                     enemy_cpus=s["enemy_cpus"] if cond != "none" else "", enemy_kb=ENEMY_KB.get(cond, ""), runtime_us=row["runtime_us"], period_us=row["period_us"],
                                     jobs=JOBS, pod_file=str(path.relative_to(HERE)), node_files=f"{NODE_DIR}/{run_id}_instance*.csv", save_results_in=f"results/{scen}/{route}/{level}_{cond}"))
    with open(HERE / "runs.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(runs[0]))
        w.writeheader()
        w.writerows(runs)
    print(f"wrote {len(runs)} pods under {HERE / 'pods'} and runs.csv")


if __name__ == "__main__":
    main()
