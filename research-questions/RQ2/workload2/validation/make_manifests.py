#!/usr/bin/env python3
"""Writes the online-validation pods of the segmentation workload for two sets of budgets (standard library only).

    python3 make_manifests.py

Inputs: budgets_empirical.csv  C_p from the observed data (bootstrap upper bound)      } exported by analysis/analysis_workload2.ipynb
        budgets_gev.csv        C_p from the GEV bound (block maxima + extremal index)   }   (section 5.1b, results/budgets_workload2_<source>.csv)
Columns: scenario, route ("Route 1", "Route 2 (m=..)", "Route 3"), p (0.1, 0.01, 0.001 or "all" for Route 3), runtime_us, period_us.

One self-contained file per estimator x scenario x route x tolerance x interference in pods/<estimator>/<scenario>/<route>/<p>_<none|memory>.yaml:
the RtClaimParameters with runtime = the budget (us) of period 100000 us, the ResourceClaimTemplate and the Pod. Route 3 has no tolerance (one budget):
hwm/all_none.yaml and all_memory.yaml. Also runs.csv (what each run is, where it runs, where its files appear on the node and where to save them) and
step5_input/<estimator>/budgets.csv (the budgets in step 4's format, for step 5's validate.py). The interference is NOT in a pod: the memory enemy is started on
the node around the runs whose file name ends in _memory.yaml (run_validation.sh does it).

To change a budget, edit the csv (or re-export it from the notebook) and run this again."""
import csv, pathlib

HERE = pathlib.Path(__file__).resolve().parent
JOBS = 10000                                   # jobs per instance: 16.7 minutes at the 100 ms period, about 10 expected exceedances at p = 1e-3
IMAGE = "pippina2/rq2-seg:v2"
NODE_DIR = "/var/lib/rq2/results/seg_validation"          # hostPath on the node; the pod writes <run id>_instance<N>.csv there
# each scenario is validated on the node that did NOT profile it (profiling: single-core on worker6, multi-core on worker7)
SCEN = {
    "multi_core": dict(short="multi", node="rt-k8s-worker-6", cpus=[1, 2], enemy_cpus="3,0", config="configs/multi_core.json"),
    "single_core": dict(short="single", node="rt-k8s-worker-7", cpus=[1], enemy_cpus="2,3,0", config="configs/single_core.json"),
}
ESTIMATORS = {"empirical": ("emp", "C_p from the observed data (bootstrap upper bound)"), "gev": ("gev", "C_p from the GEV bound (block maxima)")}
ROUTES = {"route1": ("r1", "Route 1: Q = C_p of the stress runs x alpha_drift"),
          "route2b": ("r2b", "Route 2: Q = C_p of the baselines x alpha_platform(m) x alpha_drift"),
          "hwm": ("hwm", "Route 3 (HWM): Q = largest C of the stress runs x alpha_drift (one budget for every tolerance)")}
TOL = {"0.1": "p1e-1", "0.01": "p1e-2", "0.001": "p1e-3"}
COND = {"none": ("none", "without interference"), "memory": ("mem", "with the memory enemy (started on the node around the run)")}


def route_key(label):
    return "route1" if label.startswith("Route 1") else "route2b" if label.startswith("Route 2") else "hwm"


def pod_file(est, scen, route, ptag, cond, row):
    s = SCEN[scen]
    rshort, rdesc = ROUTES[route]
    cshort, cdesc = COND[cond]
    eshort, edesc = ESTIMATORS[est]
    run_id = f"rq2-val-seg-{s['short']}-{eshort}-{rshort}-{ptag}-{cshort}"
    runtime, period = int(row["runtime_us"]), int(row["period_us"])
    text = f"""# id: {run_id}
# Online validation of the segmentation workload, {scen.replace('_', '-')}, budgets with {edesc}; {rdesc}
# {'no tolerance (one budget for every p)' if row['p'] == 'all' else 'tolerance p = ' + row['p']}, {cdesc}
# Reservation: runtime {runtime} us of period {period} us (Q/T = {runtime / period:.3f}), from budgets_{est}.csv. {JOBS} jobs per instance; cpus {s['cpus']}; pinned to {s['node']}.
# Generated by make_manifests.py: edit the budgets csv and regenerate instead of editing this file.
---
apiVersion: rt.resource.example.com/v1alpha1
kind: RtClaimParameters
metadata: {{ namespace: rq2, name: "{run_id}-params" }}
spec: {{ count: {len(s['cpus'])}, runtime: {runtime}, period: {period}, requestedCpus: {s['cpus']} }}
---
apiVersion: resource.k8s.io/v1alpha2
kind: ResourceClaimTemplate
metadata: {{ namespace: rq2, name: "{run_id}-claim" }}
spec:
  spec:
    resourceClassName: rt.example.com
    parametersRef: {{ apiGroup: rt.resource.example.com, kind: RtClaimParameters, name: "{run_id}-params" }}
---
apiVersion: v1
kind: Pod
metadata:
  namespace: rq2
  name: "{run_id}"
  labels: {{ app: rq2-workload, role: worker, validation: "true", interference: "{cond}", estimator: "{est}" }}
spec:
  restartPolicy: Never
  nodeSelector: {{ experiment-model: rq2, kubernetes.io/hostname: {s['node']} }}
  tolerations: [{{ operator: Exists }}]
  containers:
    - name: seg
      image: {IMAGE}
      imagePullPolicy: IfNotPresent
      command: ["python3", "run.py", "{s['config']}", "period_ms={period // 1000}", "jobs={JOBS}", "output=/results/{run_id}"]
      securityContext: {{ capabilities: {{ add: ["SYS_NICE", "IPC_LOCK"] }} }}
      resources: {{ claims: [{{ name: rtcpu }}] }}
      volumeMounts: [{{ name: results, mountPath: /results }}]
  resourceClaims:
    - {{ name: rtcpu, source: {{ resourceClaimTemplateName: "{run_id}-claim" }} }}
  volumes:
    - name: results
      hostPath: {{ path: {NODE_DIR}, type: DirectoryOrCreate }}
"""
    return run_id, text


def read_budgets(est):
    path = HERE / f"budgets_{est}.csv"
    rows = {}
    for r in csv.DictReader(open(path)):
        p = r["p"] if r["p"] == "all" else f"{float(r['p']):g}"
        rows[(r["scenario"], route_key(r["route"]), p)] = dict(r, p=p, label=r["route"])
    return rows


def admitted(row):
    return str(row["admitted"]).strip().lower() == "true"


def main():
    runs = []
    for est in ESTIMATORS:
        rows = read_budgets(est)
        for scen, s in SCEN.items():
            for route in ROUTES:
                out = HERE / "pods" / est / scen / route
                for p, ptag in (TOL.items() if route != "hwm" else [("all", "all")]):
                    row = rows[(scen, route, p)]
                    if not admitted(row):                      # the driver would reject this reservation (Q/T above the admission limit): nothing to validate
                        print(f"skipped (not admitted, Q/T = {int(row['runtime_us']) / int(row['period_us']):.2f}): {est} {scen} {route} p={p}")
                        continue
                    for cond in COND:
                        run_id, text = pod_file(est, scen, route, ptag, cond, row)
                        path = out / f"{ptag}_{cond}.yaml"
                        out.mkdir(parents=True, exist_ok=True)
                        path.write_text(text)
                        runs.append(dict(run_id=run_id, estimator=est, scenario=scen, route=route, p=p, interference=cond, node=s["node"],
                                         enemy_cpus=s["enemy_cpus"] if cond == "memory" else "", runtime_us=row["runtime_us"], period_us=row["period_us"], jobs=JOBS,
                                         pod_file=str(path.relative_to(HERE)), node_files=f"{NODE_DIR}/{run_id}_instance*.csv",
                                         save_results_in=f"results/{est}/{scen}/{route}/{ptag}_{cond}"))
        # the budgets in the format of step 4's budgets.csv, so that step 5's validate.py checks the online runs against exactly these budgets:
        #   python3 validate.py check --step4 <this folder>/step5_input/<estimator> --results <this folder>/results/<estimator>
        out5 = HERE / "step5_input" / est
        out5.mkdir(parents=True, exist_ok=True)
        with open(out5 / "budgets.csv", "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["scenario", "route", "p", "Q_ms", "Q_over_T", "runtime_us", "period_us", "admitted"])
            for (scen, route, p), r in rows.items():
                if not admitted(r):
                    continue
                label = {"route1": "Route 1", "route2b": "Route 2b" + r["label"][len("Route 2"):], "hwm": "HWM"}[route]
                for pp in ([0.001, 0.01, 0.1] if p == "all" else [float(p)]):
                    q, T = int(r["runtime_us"]), int(r["period_us"])
                    w.writerow([scen, label, pp, q / 1000, q / T, q, T, q / T <= 0.95])
    with open(HERE / "runs.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(runs[0]))
        w.writeheader()
        w.writerows(runs)
    print(f"wrote {len(runs)} pods under {HERE / 'pods'} and runs.csv")


if __name__ == "__main__":
    main()
